function buildSpecs(seed: Seed): ProductSpec[] {
  return seed.sp ?? defaults[seed.c];
}

function build(seed: Seed): Product {
  const stockLabel =
    seed.c === "fish"
      ? seed.st > 0
        ? `${seed.st} Available`
        : "Currently Unavailable"
      : stockLabelFor(seed.c, seed.st);

  return {
    id: slugify(seed.n),
    name: seed.n,
    slug: slugify(seed.n),
    category: seed.c,
    type: seed.t,
    price: seed.p,
    oldPrice: seed.o,
    rating: seed.r,
    reviews: seed.rv,
    image: path(seed.c, seed.img),
    images: (seed.imgs ?? [seed.img]).map((f) => path(seed.c, f)),
    description: seed.d,
    shortDescription: seed.d.split(".")[0] + ".",
    stock: seed.st,
    stockLabel,
    stockState: stockStateFor(seed.st),
    badge: seed.b,
    isLiveFish: seed.c === "fish" || seed.live,
    specs: buildSpecs(seed),
    care: seed.care ?? careDefaults[seed.c],
    featured: seed.f,
    createdAt: seed.dt ?? "2026-08-15",
    tags: [seed.c, seed.t],
  };
}

